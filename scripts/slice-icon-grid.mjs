// Slices a 4-col × 3-row 576×432 transparent PNG grid into 12 separate
// 144×144 PNG icons under assets/icons/, then regenerates src/icons-data.ts.
//
// Used when the icon set was produced as a single grid image.
// Run on demand:
//
//   node scripts/slice-icon-grid.mjs <path-to-grid.png>
//
// Falls back to scripts/build-icons.mjs's SVG-source rendering if no grid
// path is supplied (the SVG path is the historical default).

import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const HERE = dirname(fileURLToPath(import.meta.url))
const PNG_DIR = resolve(HERE, '..', 'assets', 'icons')
const DATA_OUT = resolve(HERE, '..', 'src', 'icons-data.ts')
const SIZE = 144

// Grid order must match the layout of the source grid image.
const ORDER = [
	['record-dot', 'stop', 'play', 'pause'],
	['toggle', 'next', 'prev', 'theatre'],
	['fullscreen', 'mix', 'camera', 'cuesheet'],
]

async function main() {
	const grid = process.argv[2]
	if (!grid) {
		console.error('usage: node scripts/slice-icon-grid.mjs <grid.png>')
		process.exit(2)
	}

	const meta = await sharp(grid).metadata()
	if (meta.width !== SIZE * 4 || meta.height !== SIZE * 3) {
		console.error(`grid must be ${SIZE * 4}×${SIZE * 3} (got ${meta.width}×${meta.height})`)
		process.exit(2)
	}

	await mkdir(PNG_DIR, { recursive: true })
	const dataEntries = []

	for (let row = 0; row < ORDER.length; row++) {
		for (let col = 0; col < ORDER[row].length; col++) {
			const name = ORDER[row][col]
			const buf = await sharp(grid)
				.extract({ left: col * SIZE, top: row * SIZE, width: SIZE, height: SIZE })
				.png({ compressionLevel: 9 })
				.toBuffer()
			await writeFile(`${PNG_DIR}/${name}.png`, buf)
			dataEntries.push(`\t'${name}': '${buf.toString('base64')}',`)
			console.log(`  ${name}.png (${buf.length} bytes)`)
		}
	}

	const dataSource =
		`// AUTO-GENERATED by scripts/slice-icon-grid.mjs — do not edit by hand.\n` +
		`// Run \`yarn slice:icons <grid.png>\` to regenerate from a fresh grid image.\n\n` +
		`export const ICON_PNG_BASE64: Record<string, string> = {\n` +
		dataEntries.join('\n') +
		`\n}\n`
	await writeFile(DATA_OUT, dataSource, 'utf8')

	console.log(`\nSliced ${ORDER.flat().length} icons to ${PNG_DIR}`)
	console.log(`Wrote ${DATA_OUT}`)
}

main().catch((err) => {
	console.error(err)
	process.exit(1)
})
